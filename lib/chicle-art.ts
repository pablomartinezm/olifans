// Un <path> por color con un recorte del sprite: nítido a cualquier tamaño y sin canvas (sirve en el servidor).
export function svgPaths(def: Def, x0: number, y0: number, w: number, h: number) {
  const paths: Record<string, string> = {};
  def.rows.slice(y0, y0 + h).forEach((r, y) => {
    for (let x = x0; x < Math.min(r.length, x0 + w);) {
      const ch = r[x];
      let e = x + 1;
      while (e < Math.min(r.length, x0 + w) && r[e] === ch) e++;
      const c = def.pal[ch];
      if (c) paths[c] = (paths[c] ?? "") + `M${x - x0} ${y}h${e - x}v1h${x - e}z`;
      x = e;
    }
  });
  return Object.entries(paths);
}

